"""Regenerate the UI's integer and decimal formats from pinned Unicode CLDR data."""

import hashlib
import io
import json
import pathlib
import subprocess
import tarfile
import textwrap
import urllib.request
from collections import defaultdict


VERSION = "48.2.0"
CHECKSUMS = {
    "cldr-core": "5310e0c7a06c1feb83dc8e54c8584bbe0b9c2ea8320172a18d541986b124585d",
    "cldr-numbers-full": "2d17a1453c559a62112caeed52e0bcfe3cb8539c99d239ae7b7ed4d0827679d9",
}
DESTINATION = pathlib.Path(__file__).resolve().parents[1] / "internal" / "prefs"
SYMBOLS = "symbols-numberSystem-"
DECIMALS = "decimalFormats-numberSystem-"


def open_cldr(package):
    url = f"https://registry.npmjs.org/{package}/-/{package}-{VERSION}.tgz"
    with urllib.request.urlopen(url, timeout=60) as response:
        data = response.read()
    if hashlib.sha256(data).hexdigest() != CHECKSUMS[package]:
        raise ValueError(f"Unexpected checksum for {package}@{VERSION}")
    return tarfile.open(fileobj=io.BytesIO(data), mode="r:gz")


def quote(text):
    return json.dumps(text, ensure_ascii=False).translate(
        {code: f"\\u{code:04x}" for code in (0xA0, 0x61C, 0x200E, 0x200F, 0x202F)}
    )


def formats_by_locale(archive, systems):
    by_format = defaultdict(list)
    for entry in archive:
        if not entry.name.endswith("/numbers.json"):
            continue
        locale = entry.name.split("/")[-2]
        numbers = json.load(archive.extractfile(entry))["main"][locale]["numbers"]
        default_system = numbers["defaultNumberingSystem"]
        default_pattern = numbers[DECIMALS + default_system]
        minimum = int(numbers["minimumGroupingDigits"])
        for key, symbols in numbers.items():
            if not key.startswith(SYMBOLS) or "decimal" not in symbols:
                continue
            system = key.removeprefix(SYMBOLS)
            digits = systems[system].get("_digits")
            if digits is None:  # Algorithmic numbering systems have no decimal digits.
                continue
            pattern = numbers.get(DECIMALS + system, default_pattern)["standard"]
            groups = pattern.split(";")[0].split(".")[0].split(",")
            primary = len(groups[-1]) if len(groups) > 1 else 0
            secondary = len(groups[-2]) if len(groups) > 2 else primary
            fmt = digits, symbols["decimal"], symbols["group"], symbols["minusSign"], primary, secondary, minimum
            tag = locale if system == default_system else f"{locale}-u-nu-{system}"
            by_format[fmt].append(tag)
    return sorted(by_format.items())


def main():
    with open_cldr("cldr-core") as archive:
        systems = json.load(archive.extractfile("package/supplemental/numberingSystems.json"))
        systems = systems["supplemental"]["numberingSystems"]
    with open_cldr("cldr-numbers-full") as archive:
        license_text = archive.extractfile("package/LICENSE").read()
        formats = formats_by_locale(archive, systems)

    source = [
        f"// Code generated by tools/generate_number_formats.py from Unicode CLDR {VERSION}; DO NOT EDIT.",
        "// Unicode data is covered by LICENSE-CLDR in this directory.",
        "package prefs",
        "var numberFormats = [...]NumberFormat{",
    ]
    for (digits, decimal, group, minus, primary, secondary, minimum), _ in formats:
        glyphs = ", ".join(map(quote, digits))
        source.append(
            f"{{digits: [10]string{{{glyphs}}}, decimal: {quote(decimal)}, group: {quote(group)}, "
            f"minus: {quote(minus)}, primaryGroup: {primary}, secondaryGroup: {secondary}, minimumGroupingDigits: {minimum}}},"
        )
    source += ["}", "func lookupNumberFormat(tag string) *NumberFormat {", "switch tag {"]
    for index, (_, locales) in enumerate(formats):
        tags = ", ".join(map(quote, sorted(locales)))
        source.append(
            textwrap.fill(
                tags + ":", width=110, initial_indent="case ",
                subsequent_indent="\t", break_on_hyphens=False,
            )
        )
        source.append(f"return &numberFormats[{index}]")
    source += ["}", "return nil", "}"]
    go = subprocess.run(["gofmt"], input="\n".join(source), capture_output=True, text=True, check=True)
    (DESTINATION / "number_formats_generated.go").write_text(go.stdout, encoding="utf-8")
    (DESTINATION / "LICENSE-CLDR").write_bytes(license_text)


if __name__ == "__main__":
    main()
