// guidCutoff is the snowflake ID of about 2025-12-14 UTC, from which items
// use the tweet ID as a non-permalink GUID.
const guidCutoff int64 = 2000000000000000000

func textFuncs() texttemplate.FuncMap {
	return texttemplate.FuncMap{
		"xmlEscape": xmlEscape,
		"picURL":    utils.PicURL,
		"rssTweet":  rssTweet,
	}
}

func rssTitle(t *types.Tweet, retweet string) string {
	prefix := ""
	switch {
	case t.Pinned:
		prefix = "Pinned: "
	case retweet != "":
		prefix = "RT by @" + retweet + ": "
	case len(t.Reply) > 0:
		prefix = "R to @" + t.Reply[0] + ": "
	}
	// Nim's splitWhitespace splits on ASCII whitespace only
	words := strings.FieldsFunc(formatters.StripHTML(t.Text, false), func(r rune) bool {
		return strings.ContainsRune(" \t\v\r\n\f", r)
	})
	text := xmlEscape(strings.Join(words, " "))
	// article tweets' text is just the article link; the title says more
	if t.ArticlePreview != nil && t.ArticlePreview.Title != "" {
		return prefix + xmlEscape(t.ArticlePreview.Title)
	}
	if text != "" {
		return prefix + text
	}
	result := ""
	if len(t.Media) > 0 {
		result = prefix
		first := t.Media[0].Kind
		if slices.ContainsFunc(t.Media, func(m types.Media) bool { return m.Kind != first }) {
			result += "Media"
		} else {
			switch first {
			case types.PhotoMedia:
				result += "Image"
			case types.VideoMedia:
				result += "Video"
			case types.GifMedia:
				result += "Gif"
			}
		}
	}
	if result == "" && t.Card != nil && t.Card.Kind != types.CardHidden &&
		t.Card.Kind != types.CardUnknown && t.Card.Title != "" {
		result = prefix + xmlEscape(t.Card.Title)
	}
	return result
}

func rssDescription(desc string, cfg *config.Config) string {
	return xmlEscape("Twitter feed for: " + desc + ". Generated by " + cfg.URLPrefix() + "\n")
}

type rssCardData struct {
	C           *types.Card
	Prefix      string
	Link, Title string
	DestText    string
}

type rssMediaItem struct {
	Kind              types.MediaKind
	Src, Link, Poster string
}

type rssTweetData struct {
	T       *types.Tweet
	Prefix  string
	Text    string
	Media   []rssMediaItem
	Card    *rssCardData
	Poll    []string
	Votes   string
	Status  string
	Note    string
	Quote   *types.Tweet
	QLink   string
	Cfg     *config.Config
	Prefs   *prefs.Prefs
	Article *types.ArticlePreview
}

// rssTweet renders an item description (renderRssTweet).
func rssTweet(t *types.Tweet, cfg *config.Config, p *prefs.Prefs) string {
	if t.Retweet != nil {
		t = t.Retweet
	}
	prefix := cfg.URLPrefix()
	d := rssTweetData{T: t, Prefix: prefix, Cfg: cfg, Prefs: p, Article: t.ArticlePreview}
	if text := formatters.ReplaceURLs(t.Text, p, prefix); text != "" {
		d.Text = strings.ReplaceAll(text, "\n", "<br>\n")
	}
	switch {
	case len(t.Media) > 0:
		for _, m := range t.Media {
			item := rssMediaItem{Kind: m.Kind}
			switch m.Kind {
			case types.PhotoMedia:
				item.Src = prefix + utils.PicURL(m.Photo.URL)
			case types.VideoMedia:
				item.Link = prefix + formatters.TweetLink(t, true)
				item.Src = prefix + utils.PicURL(m.Video.Thumb)
			case types.GifMedia:
				item.Poster = prefix + utils.PicURL(m.Gif.Thumb)
				item.Src = prefix + utils.PicURL(m.Gif.URL)
			}
			d.Media = append(d.Media, item)
		}
	case t.Card != nil && t.Card.Kind != types.CardHidden && t.Card.Kind != types.CardUnknown:
		c := &rssCardData{C: t.Card, Prefix: prefix, Title: xmlEscape(t.Card.Title)}
		if strings.HasPrefix(t.Card.URL, "/") {
			c.Link = prefix + t.Card.URL
		} else {
			c.Link = formatters.ReplaceURLs(t.Card.URL, p, "")
		}
		c.DestText = xmlEscape(c.Link)
		if t.Card.Dest != "" {
			c.DestText = xmlEscape(t.Card.Dest)
		}
		d.Card = c
	}
	if poll := t.Poll; poll != nil {
		for i, option := range poll.Options {
			var perc float64
			if poll.Votes > 0 && i < len(poll.Values) {
				perc = float64(poll.Values[i]) / float64(poll.Votes) * 100
			}
			d.Poll = append(d.Poll, pollPercent(perc, 0)+"% — "+xmlEscape(option))
		}
		d.Votes = insertSep(poll.Votes)
		d.Status = xmlEscape(poll.Status)
	}
	if t.Note != "" && !p.HideCommunityNotes {
		d.Note = formatters.ReplaceURLs(t.Note, p, prefix)
	}
	if t.Quote != nil && t.Quote.Available {
		d.Quote = t.Quote
		d.QLink = prefix + formatters.TweetLink(t.Quote, true)
	}
	return execText("rssTweet", d)
}

type rssItem struct {
	Title, Username, Description, PubDate, Link string
	ID                                          int64
	GlobalGUID                                  bool
}

func rssItems(threads []types.Tweets, cfg *config.Config, p *prefs.Prefs, userID string) []rssItem {
	prefix := cfg.URLPrefix()
	var links []string
	var items []rssItem
	for _, thread := range threads {
		for _, t := range thread {
			if userID != "" && t.User.ID != userID {
				continue
			}
			retweet := ""
			if t.Retweet != nil {
				retweet = t.User.Username
				t = t.Retweet
			}
			link := formatters.TweetLink(t, true)
			if slices.Contains(links, link) {
				continue
			}
			links = append(links, link)
			items = append(items, rssItem{
				Title:       rssTitle(t, retweet),
				Username:    t.User.Username,
				Description: strings.Trim(rssTweet(t, cfg, p), "\n"),
				PubDate:     formatters.Rfc822Time(t.Time),
				Link:        prefix + link,
				ID:          t.ID,
				GlobalGUID:  t.ID >= guidCutoff,
			})
		}
	}
	return items
}

// tweetsWithPinned inserts the pinned tweet before the first older tweet,
// without modifying the profile's timeline.
func tweetsWithPinned(profile types.Profile) []types.Tweets {
	result := profile.Tweets.Content
	if profile.Pinned == nil || len(result) == 0 {
		return result
	}
	pinned := profile.Pinned
	for ti, thread := range result {
		for i, t := range thread {
			if t.ID < pinned.ID {
				out := slices.Clone(result)
				out[ti] = slices.Insert(slices.Clone(thread), i, pinned)
				return out
			}
		}
	}
	return result
}

type rssChannel struct {
	Prefix, Username, Title, Link, SelfLink, Description, Pic string
	HasTweets                                                 bool
	Items                                                     []rssItem
}

// RenderTimelineRss renders a profile's RSS feed. multi is set for a
// comma-separated list of users.
func RenderTimelineRss(profile types.Profile, cfg *config.Config, p *prefs.Prefs, multi bool) string {
	prefix := cfg.URLPrefix()
	handle := "@" + profile.User.Username
	if multi {
		handle = profile.User.Username
	}
	title := profile.User.Fullname
	if !multi {
		title += " / " + handle
	}
	tweets := tweetsWithPinned(profile)
	return execText("timelineRss", rssChannel{
		Prefix:      prefix,
		Username:    profile.User.Username,
		Title:       formatters.SanitizeXML(xmlEscape(title)),
		Description: rssDescription(handle, cfg),
		Pic:         utils.PicURL(formatters.UserPic(profile.User.UserPic, "_400x400")),
		HasTweets:   len(tweets) > 0,
		Items:       rssItems(tweets, cfg, p, profile.User.ID),
	})
}

// RenderListRss renders a list's RSS feed.
func RenderListRss(tweets []types.Tweets, l types.List, cfg *config.Config, p *prefs.Prefs) string {
	link := cfg.URLPrefix() + "/i/lists/" + l.ID
	return execText("listRss", rssChannel{
		Link:        link,
		Title:       xmlEscape(l.Name) + " / @" + l.Username,
		Description: rssDescription(l.Name+" by @"+l.Username, cfg),
		Items:       rssItems(tweets, cfg, p, ""),
	})
}

// RenderCommunityNotesRss renders the community notes feed; tab is
// "helpful" or "new". Notes are always shown, whatever the preferences.
func RenderCommunityNotesRss(tweets []types.Tweets, tab string, cfg *config.Config, p *prefs.Prefs) string {
	path, label := "/i/communitynotes", "Rated Helpful"
	if tab == "new" {
		path, label = "/i/communitynotes/new", "New"
	}
	withNotes := *p
	withNotes.HideCommunityNotes = false
	return execText("communityNotesRss", rssChannel{
		Prefix:      cfg.URLPrefix(),
		Link:        path,
		Title:       label,
		Description: rssDescription("Community Notes ("+label+")", cfg),
		Items:       rssItems(tweets, cfg, &withNotes, ""),
	})
}

// RenderSearchRss renders a search's RSS feed. param is unused, as in Nim.
func RenderSearchRss(tweets []types.Tweets, name, param string, cfg *config.Config, p *prefs.Prefs) string {
	escName := xmlEscape(name)
	return execText("searchRss", rssChannel{
		Link:        cfg.URLPrefix() + "/search",
		Title:       escName,
		Description: rssDescription("Search \""+name+"\"", cfg),
		Items:       rssItems(tweets, cfg, p, ""),
	})
}

// GenerateOpenSearchXML renders the OpenSearch description document.
func GenerateOpenSearchXML(name, hostname, url string) string {
	return execText("opensearch", map[string]string{"Name": name, "Hostname": hostname, "URL": url})
}
