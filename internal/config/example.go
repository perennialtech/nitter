package config

import (
	"bytes"
	"strings"
)

// Section is one section of nitter.example.conf.
type Section struct {
	Name    string
	Doc     string
	Entries []Entry
}

// Entry is one documented key = value line of nitter.example.conf.
type Entry struct {
	Key   string
	Value string
	Doc   string
}

// ExampleSections documents the sections defined by Options.
func ExampleSections() []Section {
	var out []Section
	for _, sd := range sectionDocs {
		s := Section{Name: sd.Name, Doc: sd.Doc}
		for _, o := range Options {
			if o.Section == sd.Name {
				s.Entries = append(s.Entries, Entry{Key: o.Key, Value: o.Literal(), Doc: o.Doc})
			}
		}
		out = append(out, s)
	}
	return out
}

// The headers are one paragraph per line; comment wraps them.
const confHeader = "Nitter configuration. Copy this file to nitter.conf, or point " +
	"NITTER_CONF_FILE at your copy, and change what you need.\n\n" +
	"Each value shown is the default. A missing key or an empty value uses " +
	"the default, and unknown keys are ignored. Strings may be double-quoted. " +
	"Booleans are true or false, or yes/no, on/off, y/n or 1/0.\n\n" +
	"Generated by make generate from internal/config/options.go and " +
	"internal/prefs/prefs.go; change the descriptions and defaults there."

// ExampleConf renders nitter.example.conf.
func ExampleConf(sections []Section) []byte {
	var b bytes.Buffer
	comment(&b, confHeader)
	for _, s := range sections {
		b.WriteString("\n[" + s.Name + "]\n")
		comment(&b, s.Doc)
		for _, e := range s.Entries {
			b.WriteString("\n")
			comment(&b, e.Doc)
			b.WriteString(e.Key + " = " + e.Value + "\n")
		}
	}
	return b.Bytes()
}

const envHeader = "Environment variables Nitter reads. Use this file with " +
	"docker run --env-file, Compose's env_file or systemd's EnvironmentFile, " +
	"or set the variables in the shell.\n\n" +
	"Each value shown is the default. An unset or empty variable uses the default.\n\n" +
	"Generated by make generate from internal/config/options.go; change the " +
	"descriptions and defaults there."

// ExampleEnv renders nitter.example.env.
func ExampleEnv() []byte {
	var b bytes.Buffer
	comment(&b, envHeader)
	for _, e := range EnvVars {
		b.WriteString("\n")
		doc := e.Doc
		if e.Secret {
			doc += " Secret: keep it out of version control, logs and images."
		}
		comment(&b, doc)
		b.WriteString(e.Name + "=" + e.Default + "\n")
	}
	return b.Bytes()
}

// commentWidth is the widest a wrapped comment line may be, including "# ".
const commentWidth = 72

// comment writes text as # lines, wrapping each line of text at word
// boundaries. A blank line in text becomes a lone #.
func comment(b *bytes.Buffer, text string) {
	for _, line := range strings.Split(text, "\n") {
		words := strings.Fields(line)
		if len(words) == 0 {
			b.WriteString("#\n")
			continue
		}
		cur := "#"
		for _, w := range words {
			if len(cur) > 1 && len(cur)+1+len(w) > commentWidth {
				b.WriteString(cur + "\n")
				cur = "#"
			}
			cur += " " + w
		}
		b.WriteString(cur + "\n")
	}
}
